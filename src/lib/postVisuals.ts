function getStableSeed(value: string) {
  return value.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
}

function getTopicMatchedImage(post: PostMeta) {
  const haystack = [post.slug, post.title, post.summary, ...(post.tags || [])]
    .join(' ')
    .toLowerCase();

  return topicImageRules.find((rule) => {
    const matchesCategory = !rule.categories || rule.categories.includes(post.category);
    const matchesKeyword = rule.keywords.some((keyword) => haystack.includes(keyword.toLowerCase()));

    return matchesCategory && matchesKeyword;
  })?.image || null;
}

function uniqueImages(images: Array<string | null | undefined>) {
  return images.filter((image, index, source): image is string => Boolean(image) && source.indexOf(image) === index);
}

export function getCategoryLabel(category: string) {
  return categoryThemes[category]?.label || categoryThemes['기타'].label;
}

export function getPostVisuals(post: PostMeta) {
  const category = post.category || '기타';
  const theme = categoryThemes[category] || categoryThemes['기타'];
  const seedKey = post.slug || post.title || category;
  const imageIndex = getStableSeed(seedKey) % theme.images.length;
  const fallbackImage = theme.images[imageIndex] || categoryThemes['기타'].images[0];
  const topicImage = getTopicMatchedImage(post);
  const heroImage = LOCAL_IMAGES[post.slug] || topicImage || post.thumbnailUrl || fallbackImage;
  const galleryImages = uniqueImages([heroImage, topicImage, ...theme.images, fallbackImage]).slice(0, 4);

  return {
    ...theme,
    categoryLabel: theme.label,
    heroImage,
    fallbackImage,
    galleryImages,
    coverImage: heroImage,
  };
}

export function getPostVisualsForList(posts: PostMeta[]) {
  const usedImages = new Set<string>();

  return posts.map((post, index) => {
    const visuals = getPostVisuals(post);
    const category = post.category || '기타';
    const theme = categoryThemes[category] || categoryThemes['기타'];
    const listPool = listImagePools[category] || listImagePools['명소'] || [];
    const categoryCandidates = uniqueImages([
      visuals.heroImage,
      ...visuals.galleryImages,
      ...listPool,
      ...theme.images,
      visuals.fallbackImage,
    ]);
    const fallbackCandidates = uniqueImages([
      ...sharedListImagePool,
      ...visuals.galleryImages,
      visuals.heroImage,
    ]);
    const candidates = uniqueImages([
      ...categoryCandidates,
      ...fallbackCandidates,
    ]);

    const primaryOffset = categoryCandidates.length ? index % categoryCandidates.length : 0;
    const orderedPrimaryCandidates = [
      ...categoryCandidates.slice(primaryOffset),
      ...categoryCandidates.slice(0, primaryOffset),
    ];
    const fallbackOffset = fallbackCandidates.length ? index % fallbackCandidates.length : 0;
    const orderedFallbackCandidates = [
      ...fallbackCandidates.slice(fallbackOffset),
      ...fallbackCandidates.slice(0, fallbackOffset),
    ];
    const heroImage = orderedPrimaryCandidates.find((image) => !usedImages.has(image))
      || orderedFallbackCandidates.find((image) => !usedImages.has(image))
      || visuals.heroImage;

    usedImages.add(heroImage);

    return {
      ...post,
      ...visuals,
      heroImage,
      coverImage: heroImage,
      galleryImages: uniqueImages([heroImage, ...visuals.galleryImages, ...candidates]).slice(0, 4),
    };
  });
}
